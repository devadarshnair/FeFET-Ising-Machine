             "* tcam2f_frozen: the same cell with frozen-domain FeFETs (nanosecond searches only; start",
             "* every FeFET from a saved state with .ic on its node m). Checked against tcam2f in test 3b.",
             ".subckt tcam2f_frozen sl slb ml scl pw params: dvgl=0 dvgr=0",
             "XL sl ml scl pw fefet_c16_frozen dvg={dvgl}",
             "XR slb ml scl pw fefet_c16_frozen dvg={dvgr}",
             ".ends tcam2f_frozen",
             "",
             "* mlpre: match-line precharge pMOS from vdd, gate preb (low = precharge).",
