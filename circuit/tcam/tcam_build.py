"""Building blocks for the FeFET TCAM decks (2-FeFET cell of Ni et al., Nature Electronics 2019).

Cell (tcam2f): FeFET-L gate on SL, FeFET-R gate on SLB, both drains on the match line ML, both
sources on the source line ScL, both bodies on the row well PW.
  stored '0' = L low V_th, R high V_th;  stored '1' = L high, R low;  stored 'X' = both high.
  search '1': SL = V_S, SLB = 0;  search '0': SL = 0, SLB = V_S;  search 'X': SL = SLB = 0.
  A mismatch puts V_S on a low-V_th FeFET, which discharges the precharged ML.
Periphery (stand-in 45 nm MOSFETs): pMOS precharge, two-inverter sense amplifier, CMOS
search-line drivers on their own supply V_S. Wire parasitics per cell: ML 3.2 ohm (Ni 2019 SI)
and 0.1 fF; 0.1 fF per search line (our estimate for a ~0.5 um cell pitch at 45 nm).
"""
