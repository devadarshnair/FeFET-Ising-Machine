TCAM = REPO / "circuit" / "tcam"
VDD = 1.0          # precharge and sense-amplifier supply
VS = 1.1           # search-line high level (between the two thresholds, 0.65 and 1.68 V)
R_ML, C_ML, C_SL, C_SA_LOAD = 3.2, 0.1e-15, 0.1e-15, 1e-15
N_DOM = 16


