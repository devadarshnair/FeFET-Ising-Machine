def deck_header(title, comments):
    head = [f"* {title}"] + [f"* {c}" for c in comments]
    head += [".include ../../device/ngspice/fefet_preisach.lib",
             ".include ../../models/mosfet/standin45_bsim4.lib",
             ".include tcam_cells.lib",
             ".options reltol=1e-3 abstol=1e-15 method=gear"]
    return head


def fefet_states(bit):
    """(left, right) state names for a stored bit."""
    return {"0": ("low", "high"), "1": ("high", "low"), "X": ("high", "high")}[bit]


def sl_levels(key):
    """(SL active?, SLB active?) for a search key."""
    return {"1": (True, False), "0": (False, True), "X": (False, False)}[key]


def mismatches(stored, key):
    return sum(1 for s, k in zip(stored, key) if s != "X" and k != "X" and s != k)


def cell_instance(name, sl, slb, ml, snaps, left, right, dvgl=0.0, dvgr=0.0, frozen=False):
    sl_snap, sr_snap = snaps[left], snaps[right]
    items = [f"dvgl={dvgl:.6g}", f"dvgr={dvgr:.6g}"]
    if not frozen:
        items += [f"xl{i}={v:.9g}" for i, v in enumerate(sl_snap["x"], 1)]
        items += [f"xr{i}={v:.9g}" for i, v in enumerate(sr_snap["x"], 1)]
    cell = "tcam2f_frozen" if frozen else "tcam2f"
    line = fd.wrap_cmd(f"{name} {sl} {slb} {ml} 0 0 {cell}", items, per_line=8)
    n = name.lower()
    return line + f"\n.ic v({n}.xl.m)={sl_snap['vm']:.9g} v({n}.xr.m)={sr_snap['vm']:.9g}"


def word(w, stored, key, snaps, dvg=None, frozen=False):
    """Netlist lines of one word: supplies, SL drivers, cells, ML wire, precharge and SA.
    dvg: optional list of (dvgl, dvgr) per cell. Shared nodes: preb, in_act, and ground."""
    n = len(stored)
    lines = [f"* word {w}: stored {''.join(stored)} key {''.join(key)} -> {mismatches(stored, key)} mismatch(es)",
             f"Vdd{w} vdd{w} 0 {VDD}", f"Vs{w} vs{w} 0 {VS}"]
    for j in range(n):
        a, b = sl_levels(key[j])
        sl, slb = f"sl{w}_{j}", f"slb{w}_{j}"
        lines.append(f"Xd{w}_{j}a {'in_act' if a else f'vs{w}'} {sl} vs{w} sldrv")
        lines.append(f"Xd{w}_{j}b {'in_act' if b else f'vs{w}'} {slb} vs{w} sldrv")
        lines.append(f"Cs{w}_{j}a {sl} 0 {C_SL:.3g}")
        lines.append(f"Cs{w}_{j}b {slb} 0 {C_SL:.3g}")
        left, right = fefet_states(stored[j])
        dl, dr = dvg[j] if dvg else (0.0, 0.0)
        lines.append(cell_instance(f"Xc{w}_{j}", sl, slb, f"ml{w}_{j}", snaps, left, right, dl, dr, frozen))
        lines.append(f"Cm{w}_{j} ml{w}_{j} 0 {C_ML:.3g}")
        if j + 1 < n:
            lines.append(f"Rm{w}_{j} ml{w}_{j} ml{w}_{j+1} {R_ML}")
    lines.append(f"Xp{w} ml{w}_0 preb vdd{w} mlpre")
    lines.append(f"Xsa{w} ml{w}_0 miss{w} match{w} vdd{w} mlsa")
    ics = " ".join(f"v(ml{w}_{j})={VDD}" for j in range(n))
    lines.append(f".ic {ics} v(match{w})={VDD}")
    return lines


class Timing:
    """Search cycle: precharge, then the search lines are driven, then evaluation.
    Cycle k starts at t0 + k*period: preb low for [0, t_pre]; SL inputs active for
    [t_sl, t_sl + t_eval]. Two cycles are run; the second is measured."""

    def __init__(self, t_eval=2.8e-9, t_pre=0.8e-9, edge=20e-12, t0=0.2e-9):
        self.t_eval, self.t_pre, self.edge, self.t0 = t_eval, t_pre, edge, t0
        self.t_sl = t_pre + 0.2e-9
        self.period = self.t_sl + t_eval + 0.2e-9
        self.n_cycles = 2
        self.t_end = t0 + self.n_cycles * self.period

    def start(self, k):
        return self.t0 + k * self.period

    def sl_mid(self, k):
        """50 % point of the driver-input edge that starts the search in cycle k."""
        return self.start(k) + self.t_sl + self.edge / 2

    def sources(self):
        pre, act = [(0.0, 0.0)], [(0.0, VS)]
        for k in range(self.n_cycles):
            s = self.start(k)
            pre += [(s + self.t_pre, 0.0), (s + self.t_pre + self.edge, VDD),
                    (s + self.period - self.edge, VDD), (s + self.period, 0.0)]
            act += [(s + self.t_sl, VS), (s + self.t_sl + self.edge, 0.0),
                    (s + self.t_sl + self.t_eval, 0.0), (s + self.t_sl + self.t_eval + self.edge, VS)]
        return [fd.pwl("Vpreb", "preb", pre), fd.pwl("Vact", "in_act", act)]


def search_deck(title, comments, words, timing, out_csv, measure_only=False):
    """words: list of line-lists from word(). Default: saves ML, miss and the two supply currents per
    word (waveforms, for the nominal decks). measure_only=True (Monte Carlo): no waveform file; ngspice
    measures, for cycle 2 of every word w, the discharge time td<w> (search-line edge to SA output at
    VDD/2), the SA output at the end of the window mf<w>, and the supply charges qd<w>, qs<w>. The
    numbers appear as 'name = value' lines in the ngspice log (read by meas_from_log())."""
    lines = deck_header(title, comments) + timing.sources()
    vecs = []
    for w, wl in enumerate(words):
        lines += wl
        vecs += [f"v(ml{w}_0)", f"v(miss{w})", f"i(vdd{w})", f"i(vs{w})"]
    if not measure_only:
        lines += fd.control_block(timing.t_end, out_csv, vecs, tmax=5e-12)
        return "\n".join(lines) + "\n"
    t_sl, t_stop = timing.sl_mid(1), timing.sl_mid(1) + timing.t_eval
    c0, c1 = timing.start(1), timing.start(1) + timing.period
    lines += [".control", fd.wrap_cmd("save", vecs), f"tran 1n {timing.t_end:.12g} 0 5e-12 uic"]
    for w in range(len(words)):
        # supply charge: trapezoid over every time point (control-language integ), read at the cycle
        # edges. 'meas ... integ' was 2-5 % off against the trapezoid on the same run, so it is not used.
        lines += [f"meas tran td{w} trig at={t_sl:.12g} targ v(miss{w}) val={VDD / 2} rise=1 td={t_sl:.12g}",
                  f"meas tran mf{w} find v(miss{w}) at={t_stop - 50e-12:.12g}",
                  f"let qvd{w} = integ(i(vdd{w}))", f"let qvs{w} = integ(i(vs{w}))",
                  f"meas tran qda{w} find qvd{w} at={c0:.12g}", f"meas tran qdb{w} find qvd{w} at={c1:.12g}",
                  f"meas tran qsa{w} find qvs{w} at={c0:.12g}", f"meas tran qsb{w} find qvs{w} at={c1:.12g}"]
    lines += [".endc", ".end"]
    return "\n".join(lines) + "\n"


def meas_from_log(path, n_words, timing):
    """Per word (t_d or inf, SA flipped, E_vdd, E_vs) from a measure_only deck's ngspice log."""
    vals = {}
    for line in Path(path).read_text().splitlines():
        parts = line.split()
        if len(parts) >= 3 and parts[1] == "=" and parts[0][:2] in ("td", "mf", "qd", "qs"):
            try:
                vals[parts[0]] = float(parts[2])
            except ValueError:
                pass
    out = []
    for w in range(n_words):
        td = vals.get(f"td{w}", float("inf"))
        if td > timing.t_eval:
            td = float("inf")
        qd = vals[f"qdb{w}"] - vals[f"qda{w}"]
        qs = vals[f"qsb{w}"] - vals[f"qsa{w}"]
        out.append((td, vals[f"mf{w}"] > VDD / 2, -VDD * qd, -VS * qs))
    return out


