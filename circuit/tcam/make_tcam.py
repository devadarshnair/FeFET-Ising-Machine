"""Write the TCAM decks (generated text, committed with the repo). Needs the set-C cell states saved
by the t1f MW deck (device/tb/t1f/t1f_w01.cir). Run through the memory guard:
    <python> circuit/tcam/make_tcam.py write       t3a_write.cir, t3a_disturb.cir
    <python> circuit/tcam/make_tcam.py read        t3a_read.cir (after the two decks above ran)
    <python> circuit/tcam/make_tcam.py search      t3b_word8.cir, t3c_word64_mNN.cir
    <python> circuit/tcam/make_tcam.py mc [N] [K] [S] sim/out/t3d/t3d_mcNNN.cir: N decks of K samples (default
                                                  25 x 8); S scales sigma (other S: sim/out/t3d_sNNN/)
"""
import json
import sys

import numpy as np

import tcam_build as tb
from tcam_build import TCAM, fd, read_wrdata

PATTERN = list("10110100")
SIGMA_LOW, SIGMA_HIGH = 0.10, 0.15        # Ni 2019 SI Fig. 5: sigma(V_th) of low / high V_th FeFETs
W_EDGE, W_PULSE, V_W, V_INH = 5e-9, 10e-6, 4.0, 2.0
ROW0_TARGET, ROW0_START, ROW1_START = list("1011X100"), list("0100X011"), list("01001X11")
WAIT = 2.0
COUNTS64 = [0, 1, 2, 8, 64]
MC_SEED = 20261031


def key_with(stored, m):
    """Binary key equal to the stored word except in its first m cells."""
    return [("1" if s == "0" else "0") if j < m else s for j, s in enumerate(stored)]


# ---------------------------------------------------------------- write, inhibit, disturb
def write_times():
    p1 = (1.5e-6, 1.5e-6 + W_PULSE + 2 * W_EDGE)                 # phase 1: all gates -V_W
    p2 = (p1[1] + 2e-6, p1[1] + 2e-6 + W_PULSE + 2 * W_EDGE)     # phase 2: chosen gates +V_W
    return p1, p2, p2[1] + WAIT


def pulse_pts(t0, t1, amp, edge):
    return [(t0, 0.0), (t0 + edge, amp), (t1 - edge, amp), (t1, 0.0)]


def write_deck(snaps):
    p1, p2, t_end = write_times()
    lines = tb.deck_header("t3a_write.cir -- generated by circuit/tcam/make_tcam.py write", [
        "Test 3a: write one 8-cell word (row 0) with the two-phase scheme while a second word (row 1)",
        "shares the same gate columns and is inhibited with V_W/2 on its ML, ScL and well.",
        f"Phase 1 ({p1[0]*1e6:.1f}-{p1[1]*1e6:.2f} us): every gate line at -{V_W} V (row 0 -> high V_th); row 1 lines at -{V_INH} V.",
        f"Phase 2 ({p2[0]*1e6:.1f}-{p2[1]*1e6:.2f} us): gate lines of the FeFETs that must be low V_th at +{V_W} V,",
        f"the rest at 0 V; row 1 lines at +{V_INH} V. Row 0 ML, ScL and well stay at 0 V (Ni 2019).",
        f"Row 0 starts as {''.join(ROW0_START)} and is written to {''.join(ROW0_TARGET)}; row 1 holds "
        f"{''.join(ROW1_START)}. States saved {WAIT:.0f} s after the write.",
        "The row-1 well, ML and ScL swing to -2 V: this needs a separate (triple) well per row."])
    inh = [(0.0, 0.0), (p1[0] - 0.5e-6, 0.0), (p1[0] - 0.45e-6, -V_INH), (p1[1] + 0.45e-6, -V_INH),
           (p1[1] + 0.5e-6, 0.0), (p2[0] - 0.5e-6, 0.0), (p2[0] - 0.45e-6, V_INH), (p2[1] + 0.45e-6, V_INH),
           (p2[1] + 0.5e-6, 0.0)]
    lines.append(fd.pwl("Vinh", "inh", inh))
    vecs = []
    for j, bit in enumerate(ROW0_TARGET):
        left, right = tb.fefet_states(bit)
        for side, state in (("a", left), ("b", right)):
            pts = [(0.0, 0.0)] + pulse_pts(*p1, -V_W, W_EDGE)
            if state == "low":
                pts += pulse_pts(*p2, V_W, W_EDGE)
            lines.append(fd.pwl(f"Vg{j}{side}", f"g{j}{side}", pts))
    for r, start, node in ((0, ROW0_START, "0"), (1, ROW1_START, "inh")):
        for j, bit in enumerate(start):
            left, right = tb.fefet_states(bit)
            name = f"Xc{r}_{j}"
            line = tb.cell_instance(name, f"g{j}a", f"g{j}b", node, snaps, left, right)
            lines.append(line.replace(f"g{j}b {node} 0 0 tcam2f", f"g{j}b {node} {node} {node} tcam2f"))
            vecs += fd.state_vectors(f"{name.lower()}.xl") + fd.state_vectors(f"{name.lower()}.xr")
    lines += fd.control_block(t_end, "sim/out/t3a/t3a_write.csv", vecs)
    return "\n".join(lines) + "\n"


DISTURB = [("lp", "low", +V_INH), ("lm", "low", -V_INH), ("hp", "high", +V_INH), ("hm", "high", -V_INH),
           ("l0", "low", 0.0), ("h0", "high", 0.0),
           # information only: the same stress at V_W/3 = +-1.33 V (a V/3 inhibit scheme)
           ("lp3", "low", +V_W / 3), ("lm3", "low", -V_W / 3), ("hp3", "high", +V_W / 3), ("hm3", "high", -V_W / 3)]
T_STRESS = 255 * W_PULSE


def disturb_deck(snaps):
    t0, t1 = 1e-6, 1e-6 + T_STRESS + 2 * W_EDGE
    lines = tb.deck_header("t3a_disturb.cir -- generated by circuit/tcam/make_tcam.py write", [
        "Test 3a disturb: single set-C FeFETs (low or high V_th) at the inhibit voltage +-2 V for 255 x 10 us",
        "(one continuous 2.55 ms stress = 255 other rows written once), then 2 s at 0 V. l0/h0: no stress.",
        "lp3 ... hm3: the same at +-V_W/3 = +-1.33 V (information only)."])
    vecs = []
    for name, state, v in DISTURB:
        pts = [(0.0, 0.0)] + (pulse_pts(t0, t1, v, W_EDGE) if v else [])
        lines.append(fd.pwl(f"Vg_{name}", f"g_{name}", pts))
        lines.append(fd.instance_from_snapshot(f"X{name}", f"g_{name} 0 0 0", "fefet_c16", snaps[state]))
        vecs += fd.state_vectors(f"x{name}")
    lines += fd.control_block(t1 + WAIT, "sim/out/t3a/t3a_disturb.csv", vecs)
    return "\n".join(lines) + "\n"


def read_deck():
    wr = read_wrdata(tb.REPO / "sim" / "out" / "t3a" / "t3a_write.csv")
    di = read_wrdata(tb.REPO / "sim" / "out" / "t3a" / "t3a_disturb.csv")
    insts = []
    for r in (0, 1):
        for j in range(8):
            for side in ("l", "r"):
                insts.append((f"r{r}c{j}{side}", "fefet_c16", fd.snapshot(wr, f"xc{r}_{j}.x{side}", wr["time"][-1])))
    insts += [(f"d{name}", "fefet_c16", fd.snapshot(di, f"x{name}", di["time"][-1])) for name, *_ in DISTURB]
    text = fd.read_deck("t3a_read.cir -- generated by circuit/tcam/make_tcam.py read",
                        ["Test 3a: read every FeFET of the write and disturb decks (fresh instances from their",
                         "saved states). r<row>c<cell><l|r>: array FeFETs; d<name>: disturb FeFETs."],
                        insts, fd.ReadOnly(-0.2, 2.4), "sim/out/t3a/t3a_read.csv")
    return text.replace(".include ../ngspice/", ".include ../../device/ngspice/")


# ---------------------------------------------------------------- search decks
def word8_cases():
    cases = [(f"count {m}", PATTERN, key_with(PATTERN, m)) for m in range(9)]
    thermo = list("11110000")
    cases += [("pricer {0,X}: 2", thermo, list("XX000000")), ("pricer {0,X}: 0", thermo, list("XXXXXXXX")),
              ("pricer {0,X}: 4", thermo, list("00000000"))]
    sx = list("1X0X1X0X")
    cases += [("stored X: 0", sx, list("10011001")), ("stored X: 2", sx, list("01111100"))]
    return cases


T8 = tb.Timing(t_eval=2.8e-9)
T64 = tb.Timing(t_eval=8.0e-9)


def word8_deck(snaps, frozen=False):
    cases = word8_cases()
    words = [tb.word(w, s, k, snaps, frozen=frozen) for w, (_, s, k) in enumerate(cases)]
    tag = "_frozen" if frozen else ""
    comments = ["Test 3b: 8-cell words (one per case), nominal devices, two search cycles (the second is measured).",
                f"VDD = {tb.VDD} V, V_S = {tb.VS} V, precharge {T8.t_pre*1e9:.1f} ns, evaluate {T8.t_eval*1e9:.1f} ns."]
    comments += [f"word {w}: {c[0]}: stored {''.join(c[1])} key {''.join(c[2])}" for w, c in enumerate(cases)]
    comments.append("FeFETs with frozen domain states (fefet_c16_frozen)." if frozen else "Full FeFET model (fefet_c16).")
    return tb.search_deck(f"t3b_word8{tag}.cir -- generated by circuit/tcam/make_tcam.py search", comments, words, T8,
                          f"sim/out/t3b/t3b_word8{tag}.csv")


def word64_deck(snaps, m):
    stored = (PATTERN * 8)
    key = key_with(stored, m)
    comments = [f"Test 3c: one 64-cell word (pattern {''.join(PATTERN)} x 8) searched with {m} mismatches.",
                "FeFETs with frozen domain states (fefet_c16_frozen), checked against the full model in 3b.",
                f"Evaluate window {T64.t_eval*1e9:.1f} ns; two cycles, the second is measured."]
    return tb.search_deck(f"t3c_word64_m{m:02d}.cir -- generated by circuit/tcam/make_tcam.py search", comments,
                          [tb.word(0, stored, key, snaps, frozen=True)], T64, f"sim/out/t3c/t3c_word64_m{m:02d}.csv")


def mc_decks(snaps, n_decks, k_samples, scale=1.0):
    """Monte Carlo: every deck holds k_samples x 9 words (counts 0..8); every FeFET gets its own
    gate-referred V_th shift, sigma by its state (low 0.10 V, high 0.15 V)."""
    rng = np.random.default_rng(MC_SEED)
    folder = "t3d" if scale == 1.0 else f"t3d_s{int(round(scale * 100)):03d}"
    s_lo, s_hi = SIGMA_LOW * scale, SIGMA_HIGH * scale
    meta = {"seed": MC_SEED, "sigma_low": s_lo, "sigma_high": s_hi, "k_samples": k_samples,
            "n_decks": n_decks, "pattern": "".join(PATTERN), "decks": []}
    deck_dir = tb.REPO / "sim" / "out" / folder     # generated, git-ignored; seed fixed
    deck_dir.mkdir(parents=True, exist_ok=True)
    for d in range(n_decks):
        words, info = [], []
        for s in range(k_samples):
            for m in range(9):
                key = key_with(PATTERN, m)
                dvg = []
                for bit in PATTERN:
                    l, r = tb.fefet_states(bit)
                    dvg.append(tuple(float(rng.normal(0, s_lo if st == "low" else s_hi)) for st in (l, r)))
                words.append(tb.word(len(words), PATTERN, key, snaps, dvg, frozen=True))
                info.append({"sample": d * k_samples + s, "count": m, "dvg": dvg})
        text = tb.search_deck(f"t3d_mc{d:03d}.cir -- generated by circuit/tcam/make_tcam.py mc",
                              [f"Test 3d Monte Carlo deck {d}: {k_samples} samples x counts 0..8, seed {MC_SEED}, "
                               f"sigma {s_lo:.3f} / {s_hi:.3f} V."],
                              words, T8, f"sim/out/{folder}/t3d_mc{d:03d}.csv", measure_only=True)
        (deck_dir / f"t3d_mc{d:03d}.cir").write_text(text.replace(".include ../../", ".include ../../../")
                                                     .replace(".include tcam_cells.lib", ".include ../../../circuit/tcam/tcam_cells.lib"))
        meta["decks"].append(info)
    (deck_dir / "t3d_mc_meta.json").write_text(json.dumps(meta))


def main():
    what = sys.argv[1]
    tb.write_lib()
    if what == "read":
        (TCAM / "t3a_read.cir").write_text(read_deck())
        print("make_tcam: wrote t3a_read.cir")
        return
    snaps = tb.device_snapshots()
    if what == "write":
        (TCAM / "t3a_write.cir").write_text(write_deck(snaps))
        (TCAM / "t3a_disturb.cir").write_text(disturb_deck(snaps))
        print("make_tcam: wrote tcam_cells.lib, t3a_write.cir, t3a_disturb.cir")
    elif what == "search":
        (TCAM / "t3b_word8.cir").write_text(word8_deck(snaps))
        (TCAM / "t3b_word8_frozen.cir").write_text(word8_deck(snaps, frozen=True))
        for m in COUNTS64:
            (TCAM / f"t3c_word64_m{m:02d}.cir").write_text(word64_deck(snaps, m))
        print("make_tcam: wrote t3b_word8.cir and the t3c_word64 decks")
    elif what == "mc":
        n = int(sys.argv[2]) if len(sys.argv) > 2 else 25
        k = int(sys.argv[3]) if len(sys.argv) > 3 else 8
        scale = float(sys.argv[4]) if len(sys.argv) > 4 else 1.0
        mc_decks(snaps, n, k, scale)
        folder = "t3d" if scale == 1.0 else f"t3d_s{int(round(scale * 100)):03d}"
        print(f"make_tcam: wrote {n} Monte Carlo decks of {k} samples in sim/out/{folder}/")


if __name__ == "__main__":
    main()
