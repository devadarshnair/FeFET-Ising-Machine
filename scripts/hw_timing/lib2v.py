"""Behavioural Verilog cell models from a Liberty file (functions of combinational output pins, simple `ff` groups), so the
Yosys netlists of timing study v1 can be simulated at gate level (zero delay) and their VCD fed to OpenSTA for activity-annotated power.

  lib2v.py <lib> <out.v> [CELL ...]     (default: every cell of the library that has a supported function)
Supported: output pins with `function`, `ff(IQ,IQN){next_state; clocked_on}` flops (no set/clear), tie cells (function "0"/"1").
"""
from __future__ import annotations

import re
import sys
from pathlib import Path


def blocks(text: str, kind: str):
    """Yield (name, body) of every `kind (name) { ... }` group with balanced braces."""
    for m in re.finditer(rf"\b{kind}\s*\(\s*\"?([\w.$]+)\"?\s*\)\s*\{{", text):
        depth, i = 1, m.end()
        while depth:
            c = text[i]
            depth += (c == "{") - (c == "}")
            i += 1
        yield m.group(1), text[m.end():i - 1]


def expr(f: str) -> str:
    f = f.strip().strip('"')
    f = re.sub(r"!\s*", "~", f)
    f = f.replace("&", "&").replace("+", "|").replace("*", "&")
    return f


def cell_model(name: str, body: str) -> str | None:
    pins = {p: b for p, b in blocks(body, "pin")}
    ins = [p for p, b in pins.items() if re.search(r"direction\s*:\s*input", b)]
    outs = [p for p, b in pins.items() if re.search(r"direction\s*:\s*output", b)]
    if not outs or re.search(r"\blatch\s*\(", body):
        return None
    ff = re.search(r"\bff\s*\(\s*\"?(\w+)\"?\s*,\s*\"?(\w+)\"?\s*\)\s*\{(.*?)\}", body, re.S)
    ports = ", ".join(ins + outs)
    lines = [f"module {name} ({ports});"] + [f"  input {p};" for p in ins] + [f"  output {p};" for p in outs]
    if ff:
        iq, iqn, fb = ff.groups()
        ns = re.search(r"next_state\s*:\s*\"([^\"]+)\"", fb)
        ck = re.search(r"clocked_on\s*:\s*\"([^\"]+)\"", fb)
        if not ns or not ck or re.search(r"\b(clear|preset)\b", fb):
            return None
        lines += [f"  reg {iq} = 1'b0;", f"  wire {iqn} = ~{iq};", f"  always @(posedge {ck.group(1).strip()}) {iq} <= {expr(ns.group(1))};"]
        for p in outs:
            fn = re.search(r"function\s*:\s*\"([^\"]+)\"", pins[p])
            if not fn:
                return None
            lines.append(f"  assign {p} = {expr(fn.group(1))};")
    else:
        for p in outs:
            fn = re.search(r"function\s*:\s*\"([^\"]+)\"", pins[p])
            if not fn:
                return None
            lines.append(f"  assign {p} = {expr(fn.group(1))};")
    lines.append("endmodule")
    return "\n".join(lines)


def main() -> int:
    text = Path(sys.argv[1]).read_text()
    want = set(sys.argv[3:])
    out = ["// generated by scripts/hw_timing/lib2v.py from the Liberty file (zero-delay behavioural cell models)"]
    for name, body in blocks(text, "cell"):
        if (want and name not in want) or "CLKGATE" in name:
            continue
        m = cell_model(name, body)
        if m:
            out.append(m)
    for x in (1, 2, 4, 8):      # integrated clock gates have a `statetable` (latch) the generic converter does not read: hand model, posedge-precontrol ICG
        out.append(f"module CLKGATETST_X{x} (CK, E, SE, GCK);\n  input CK; input E; input SE; output GCK;\n  reg lat;\n"
                   "  always @(CK or E or SE) if (!CK) lat = E | SE;\n  assign GCK = CK & lat;\nendmodule")
    Path(sys.argv[2]).write_text("\n".join(out) + "\n")
    print(f"{len(out) - 1} cell models")
    return 0


if __name__ == "__main__":
    sys.exit(main())
