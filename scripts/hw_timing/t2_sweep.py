"""timing study v2 cut-mask sweep for the pipelined select tree: writes rtl/pnr/t2_cuts.txt candidates and collects the P&R results.

  t2_sweep.py gen  <N> [<N> ...]   candidate grid (adder cuts a = 0..3 x walk cuts w = 0..4, evenly spaced) -> t2_cuts.txt (tags s<a>w<w>)
  t2_sweep.py show <out dir>       table of every selp_N*_* block: latency, post-P&R worst arrival (ns), area, cells, leakage
Runs through rtl/pnr/run_timing_v2.sh --pnr (TT_PERIOD_NS = target clock; the P&R repair_timing works toward it).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def positions(count: int, total: int, late: bool) -> list[int]:
    """`count` cut positions (1-based op numbers 1..total) spread over the op range; late=True pushes them toward the end."""
    if count == 0:
        return []
    if count == 1 and not late:
        return [max(1, total // 2)]
    pos = []
    for i in range(1, count + 1):
        f = i / count if not late else (i / count) ** 0.7
        pos.append(max(1, min(total, round(f * total))))
    return sorted(set(pos))


def masks(n: int, a: int, w: int) -> tuple[int, int]:
    lg = n.bit_length() - 1
    add = [lg] if a == 1 else positions(a, lg, False)        # a = 1: only after the root count (before the multiply)
    walk = [p for p in positions(w, lg - 1, True)]            # walk step j (0-based) cut bit j: cut after step p-1
    return sum(1 << (k - 1) for k in add), sum(1 << (p - 1) for p in walk if 1 <= p <= lg - 1)


def gen(ns: list[int]) -> None:
    lines = ["# N tag ADD_CUT WALK_CUT   (select_tree_pipe cut masks, see rtl/src/select_tree_pipe.v); generated by scripts/hw_timing/t2_sweep.py"]
    for n in ns:
        seen = set()
        for a in range(0, 4):
            for w in range(0, 5):
                m = masks(n, a, w)
                if m in seen:
                    continue
                seen.add(m)
                lines.append(f"{n} s{a}w{w} {m[0]} {m[1]}")
    (ROOT / "rtl/pnr/t2_cuts.txt").write_text("\n".join(lines) + "\n")


def custom(n: int, specs: list[str], append: bool) -> None:
    """specs like "10:2,5,8" = adder cuts after levels {10}, walk cuts after steps {2,5,8}; tag a10_w2-5-8."""
    p = ROOT / "rtl/pnr/t2_cuts.txt"
    lines = p.read_text().splitlines() if append and p.exists() else ["# N tag ADD_CUT WALK_CUT   (select_tree_pipe cut masks, see rtl/src/select_tree_pipe.v); generated by scripts/hw_timing/t2_sweep.py"]
    for sp in specs:
        a, w = sp.split(":")
        al = [int(x) for x in a.split(",") if x]
        wl = [int(x) for x in w.split(",") if x]
        tag = "a" + "-".join(map(str, al)) + "_w" + "-".join(map(str, wl))
        lines.append(f"{n} {tag} {sum(1 << (k - 1) for k in al)} {sum(1 << j for j in wl)}")
    p.write_text("\n".join(lines) + "\n")


def arrival(d: Path, f: str) -> float | None:
    p = d / f
    if not p.exists():
        return None
    m = re.search(r"^\s*([\d.]+)\s+data arrival time", p.read_text(), re.M)
    return float(m.group(1)) if m else None


def show(out: Path) -> None:
    cuts = {}
    for l in (ROOT / "rtl/pnr/t2_cuts.txt").read_text().splitlines():
        if l and not l.startswith("#"):
            n, tag, ac, wc = l.split()
            cuts[f"selp_N{n}_{tag}"] = (int(n), int(ac), int(wc))
    print(f"{'block':18s} {'lat':>3s} {'synth_ns':>8s} {'pnr_ns':>7s} {'area_um2':>9s}")
    for d in sorted(out.glob("selp_N*")):
        n, ac, wc = cuts.get(d.name, (0, 0, 0))
        lg = max(n.bit_length() - 1, 1)
        lat = 2 + bin(ac & ((1 << lg) - 1)).count("1") + bin(wc & ((1 << (lg - 1)) - 1)).count("1")
        area = re.search(r"Design area ([\d.]+) u", (d / "pnr.log").read_text()) if (d / "pnr.log").exists() else None
        pa = arrival(d, "pnr_paths.txt")
        print(f"{d.name:18s} {lat:3d} {arrival(d, 'sta_paths.txt') or 0:8.3f} {pa if pa else 0:7.3f} {area.group(1) if area else '-':>9s}")


if __name__ == "__main__":
    if sys.argv[1] == "custom":
        custom(int(sys.argv[2]), sys.argv[3:], append=False)
    elif sys.argv[1] == "gen":
        gen([int(x) for x in sys.argv[2:]])
    else:
        show(Path(sys.argv[2]))
