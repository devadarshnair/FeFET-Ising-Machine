"""Write the retention decks of test 1e (generated text, committed with the repo).

Stage 1 (--stage 1): device/tb/t1e/t1e_hold_<dev>.cir, one deck per device (a stiff device then
  cannot slow the others down). Each FeFET starts from the state saved by its MW deck 2 s after the
  last write (1 us before the in-deck read): set B after +-4.5 V / 10 us (t1d) and set C after
  +-4 V / 10 us (t1f), low and high V_th. All terminals are held at 0 V for 3.2e8 s (10 years); the
  run is forced to stop at the read times so the states can be saved there.
  Device cv (target C6): set C high V_th with +1.1 V (search level) on the gate from 0 to 1e5 s
  (1 ms ramps; a 3.2e8 s run cannot take nanosecond edges), then 0 V; it is read at 1e5 s + 2 s.
Stage 2 (--stage 2): device/tb/t1e/t1e_read.cir. One fresh FeFET per (state, hold time) starts from
  the stage-1 state and gets one read ramp (V_DS = 50 mV, as in the MW decks).
Run: scripts/run_guarded.sh <python> device/tb/make_t1e.py --stage 1   (then ngspice, then --stage 2)
"""
import argparse

from checklib import OUT, REPO, read_wrdata
import fefet_decks as fd
from make_fefet_mw import PROT_B, PROT_C, state_csv

TB = REPO / "device" / "tb" / "t1e"
HOLD_TIMES = [0.0, 1e2, 1e3, 1e4, 1e5, 1e6, 1e7, 1e8, 3.15e8]
READ = fd.ReadOnly(-1.2, 2.4)
DEVICES = {  # name: (subckt, MW-deck prefix, protocol, state)
    "bl": ("fefet_b16", "t1d", PROT_B, "low"),
    "bh": ("fefet_b16", "t1d", PROT_B, "high"),
    "cl": ("fefet_c16", "t1f", PROT_C, "low"),
    "ch": ("fefet_c16", "t1f", PROT_C, "high"),
    "cv": ("fefet_c16", "t1f", PROT_C, "high"),
}
C6_V, C6_T, C6_EDGE = 1.1, 1e5, 1e-3
C6_READ = C6_T + 2.0
T_HOLD = 3.2e8
# Every device is held only to 1.1e6 s in ngspice: the slow back-switching makes long holds very
# stiff (steps of about 5e-4 * t; 3.2e8 s did not finish in 15 min). The test point is 1e5 s; the
# 10-year value is an offline estimate (check_t1e.py, reduced model).
T_END = {name: 1.1e6 for name in ("bl", "bh", "cl", "ch", "cv")}


def hold_times(name):
    return [t for t in HOLD_TIMES if t <= T_END.get(name, T_HOLD)]


def start_snapshot(prefix, prot, state):
    path, inst = state_csv(prefix)
    t = prot.t_low if state == "low" else prot.t_high
    return fd.snapshot(read_wrdata(path), inst, t)


def hold_deck(name):
    sub, prefix, prot, state = DEVICES[name]
    what = (f"set C high V_th with +{C6_V} V on the gate until {C6_T:g} s (target C6), then 0 V" if name == "cv"
            else f"set {prefix == 't1d' and 'B' or 'C'} {state} V_th, all terminals at 0 V")
    lines = [f"* t1e_hold_{name}.cir -- generated by device/tb/make_t1e.py --stage 1",
             f"* Test 1e stage 1: hold one written FeFET for {T_END.get(name, T_HOLD):g} s: {what}.",
             "* It starts from its state 2 s after the write.",
             ".include ../../ngspice/fefet_preisach.lib",
             ".options reltol=1e-3 abstol=1e-15 method=gear"]
    t_end = T_END.get(name, T_HOLD)
    times = sorted(set(hold_times(name)[1:] + ([C6_T, C6_T + C6_EDGE, C6_READ] if name == "cv" else [])))
    lines += [f"Vbp bp 0 pwl(0 0 {' '.join(f'{t:.9g} 0' for t in times)} {t_end:g} 0)", "Rbp bp 0 1k"]
    if name == "cv":
        lines.append(f"Vc6 gc6 0 pwl(0 0 {C6_EDGE:g} {C6_V} {C6_T:.9g} {C6_V} {C6_T + C6_EDGE:.9g} 0 {T_HOLD:g} 0)")
    nodes = "gc6 0 0 0" if name == "cv" else "0 0 0 0"
    lines.append(fd.instance_from_snapshot(f"X{name}", nodes, sub, start_snapshot(prefix, prot, state)))
    vecs = fd.state_vectors(f"x{name}")
    ctrl = fd.control_block(t_end, f"sim/out/t1e/t1e_hold_{name}.csv", vecs)
    ctrl.insert(1, fd.wrap_cmd("save", vecs))
    fd.write(TB / f"t1e_hold_{name}.cir", "\n".join(lines + ctrl) + "\n")


def stage1():
    for old in TB.glob("t1e_hold*.cir"):
        old.unlink()
    for name in DEVICES:
        hold_deck(name)
    print(f"make_t1e: wrote {len(DEVICES)} hold decks in device/tb/t1e/")


def stage2():
    insts = []
    for name, (sub, *_r) in DEVICES.items():
        hold = read_wrdata(OUT / "t1e" / f"t1e_hold_{name}.csv")
        if name == "cv":
            insts.append(("cv0", sub, fd.snapshot(hold, "xcv", C6_READ)))
        else:
            insts += [(f"{name}{j}", sub, fd.snapshot(hold, f"x{name}", th)) for j, th in enumerate(hold_times(name))]
    text = fd.read_deck("t1e_read.cir -- generated by device/tb/make_t1e.py --stage 2",
                        ["Test 1e stage 2: read every held FeFET state once (a fresh instance started from",
                         "the stage-1 state). Instance <dev><j>: j = index into HOLD_TIMES of make_t1e.py;",
                         f"cv0 = the C6 device at {C6_READ:g} s."],
                        insts, READ, "sim/out/t1e/t1e_read.csv")
    fd.write(TB / "t1e_read.cir", text.replace(".include ../", ".include ../../"))
    print("make_t1e: wrote device/tb/t1e/t1e_read.cir")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", type=int, choices=[1, 2], required=True)
    (stage1 if ap.parse_args().stage == 1 else stage2)()


if __name__ == "__main__":
    main()
